async function decode(page, alt) {
  const png = PNG.sync.read(await page.getByAltText(alt).screenshot());
  const result = jsQR(new Uint8ClampedArray(png.data), png.width, png.height);
  assert.ok(result, 'Displayed QR must be decodable');
  return result.data;
}
